#!/usr/bin/env python3
"""生成两类此前没有样本的合成 profile：

1. **抽象 profile（`abst`）**：PCS → PCS。这里造**恒等**映射，于是判据很硬：
   链 `[sRGB, abstract, display]` 必须等于直接变换 `[sRGB, display]`。
2. **device link profile（`link`）**：设备 → 设备。这里造解析式映射
   `C=1-R, M=1-G, Y=1-B, K=0`，于是判据可写成闭式，不依赖参考实现。

两者都是 v4 `mAB`（A 曲线 → CLUT → B 曲线，曲线取恒等项数 0），
PCS 用 Lab（v4 的 u1Fixed16 编码：L 0..100 ↔ 0..0xFFFF，a/b -128..127 ↔ 0..0xFFFF）。

用法：python tools/gen_abst_link_profiles.py
"""

import os
import struct
import sys

sys.stdout.reconfigure(encoding="utf-8")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TESTDATA = os.path.join(ROOT, "testdata")
GRID = 2


def sf16(x):
    return struct.pack(">i", int(round(x * 65536.0)))


def identity_curves(count):
    out = b""
    for _ in range(count):
        out += b"curv" + b"\0\0\0\0" + struct.pack(">I", 0)
    return out


def mluc(text):
    raw = text.encode("utf-16-be")
    rec = struct.pack(">HHII", 0x656E, 0x5553, len(raw), 28)
    payload = b"mluc" + b"\0\0\0\0" + struct.pack(">II", 1, 12) + rec + raw
    payload += b"\0" * ((4 - len(payload) % 4) % 4)
    return payload


def xyz_tag(x, y, z):
    return b"XYZ " + b"\0\0\0\0" + sf16(x) + sf16(y) + sf16(z)


def build_lut_tag(tag_sig, in_ch, out_ch, nodes):
    """mAB / mBA：A 曲线 → CLUT → B 曲线，曲线恒等，CLUT 为 GRID^in_ch 个节点。

    nodes 按输入网格顺序（最后一维变化最快）给出，每个是 out_ch 个 u16。
    """
    body = bytearray()
    body += tag_sig + b"\0\0\0\0"
    body += struct.pack(">BBH", in_ch, out_ch, 0)
    off_pos = len(body)
    body += b"\0" * 20
    a_off = len(body)
    body += identity_curves(in_ch)
    clut_off = len(body)
    body += bytes([GRID] * in_ch + [0] * (16 - in_ch))
    body += bytes([2, 0, 0, 0])
    for node in nodes:
        body += struct.pack(">" + "H" * out_ch, *node)
    # CLUT 之后要 4 字节对齐（绝对位置）
    while len(body) % 4:
        body += b"\0"
    b_off = len(body)
    body += identity_curves(out_ch)
    struct.pack_into(">5I", body, off_pos, b_off, 0, 0, clut_off, a_off)
    return bytes(body)


def lab_enc(l, a, b):
    """v4 Lab → u1Fixed16（L 0..100 ↔ 0..0xFFFF；a/b -128..127 ↔ 0..0xFFFF）。"""
    def q(v):
        return max(0, min(0xFFFF, int(round(v * 65535.0))))

    return (q(l / 100.0), q((a + 128.0) / 255.0), q((b + 128.0) / 255.0))


def dev_enc(v):
    return max(0, min(0xFFFF, int(round(v * 65535.0))))


def write_profile(path, device_class, color_space, pcs, tags, comment):
    n = len(tags)
    offset = 132 + n * 12
    entries = b""
    blob = b""
    for sig, d in tags:
        entries += sig + struct.pack(">II", offset, len(d))
        blob += d
        offset += len(d)
        while offset % 4:
            blob += b"\0"
            offset += 1
    hdr = bytearray(128)
    hdr[4:8] = b"prb "                      # CMM
    hdr[8:12] = bytes([4, 0x30, 0, 0])       # v4.3
    hdr[12:16] = device_class.encode("latin1")
    hdr[16:20] = color_space.encode("latin1")
    hdr[20:24] = pcs.encode("latin1")
    hdr[24:36] = struct.pack(">6H", 2026, 10, 22, 0, 0, 0)
    hdr[36:40] = b"acsp"
    hdr[40:44] = b"    "
    hdr[64:68] = struct.pack(">I", 0)
    hdr[68:80] = sf16(0.9642) + sf16(1.0) + sf16(0.8249)   # D50
    hdr[80:84] = b"prb "
    out = bytes(hdr) + struct.pack(">I", n) + entries + blob
    out = struct.pack(">I", len(out)) + out[4:]
    with open(path, "wb") as f:
        f.write(out)
    print(f"  已写出 {os.path.basename(path)}（{comment}，{len(out)} 字节）")


def gen_abstract(path):
    """恒等抽象 profile：Lab → Lab，CLUT 8 个角点原样输出。"""
    nodes = []
    for r in (0, 1):
        for g in (0, 1):
            for b in (0, 1):
                nodes.append(lab_enc(r * 100.0, g * 255.0 - 128.0, b * 255.0 - 128.0))
    tags = [
        (b"desc", mluc("Synthetic abstract (identity) profile")),
        (b"cprt", mluc("Public domain test profile generated by moon_icc tools")),
        (b"A2B0", build_lut_tag(b"mAB ", 3, 3, nodes)),
    ]
    write_profile(path, "abst", "Lab ", "Lab ", tags, "恒等 PCS→PCS")


def gen_device_link(path):
    """device link：RGB → CMYK，C=1-R, M=1-G, Y=1-B, K=0。"""
    nodes = []
    for r in (0, 1):
        for g in (0, 1):
            for b in (0, 1):
                nodes.append(
                    (dev_enc(1 - r), dev_enc(1 - g), dev_enc(1 - b), dev_enc(0))
                )
    tags = [
        (b"desc", mluc("Synthetic device link RGB to CMYK profile")),
        (b"cprt", mluc("Public domain test profile generated by moon_icc tools")),
        (b"A2B0", build_lut_tag(b"mAB ", 3, 4, nodes)),
    ]
    write_profile(path, "link", "RGB ", "CMYK", tags, "RGB→CMYK 解析式")


def verify_with_lcms2():
    """用 lcms2（Pillow）确认两个 profile 能被参考实现读入。"""
    try:
        from PIL import ImageCms
    except Exception as e:  # pragma: no cover
        print(f"  跳过 lcms2 复核（{e}）")
        return
    for name in ("abstract.icc", "devicelink.icc"):
        p = os.path.join(TESTDATA, name)
        prof = ImageCms.getOpenProfile(p)
        print(
            f"  lcms2 读入 {name}: class={ImageCms.getProfileInfo(prof).splitlines()[0][:0] or ''}"
            f"desc=\"{ImageCms.getProfileDescription(prof).strip()}\""
        )


def main():
    print("生成 abst / link 合成样本")
    gen_abstract(os.path.join(TESTDATA, "abstract.icc"))
    gen_device_link(os.path.join(TESTDATA, "devicelink.icc"))
    verify_with_lcms2()
    return 0


if __name__ == "__main__":
    sys.exit(main())
